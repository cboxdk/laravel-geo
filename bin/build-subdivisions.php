<?php

declare(strict_types=1);

/**
 * Builds resources/iso-3166-2.php, every current ISO 3166-2 subdivision code with
 * its English name, from a tagged Unicode CLDR release.
 *
 *   php bin/build-subdivisions.php [release-49]
 *
 * Why CLDR: commerceguys/addressing only knows the subdivisions a postal address
 * uses (no German Länder, no Spanish autonomous communities), while CLDR tracks
 * all of ISO 3166-2 and marks abolished codes as deprecated, so a code that no
 * longer exists (the Danish counties of 2007) does not come back. It is under the
 * permissive Unicode-3.0 licence.
 *
 * Kept: idStatus "regular", plus the deprecated codes CLDR aliases with reason
 * "overlong". Those are still ISO 3166-2 codes; CLDR only prefers the territory's
 * own country code (FI-01 => AX, US-PR => PR, FR-GP => GP). Dropped: every other
 * deprecated code and the "unknown" placeholders (ESZZZZ).
 */
$release = $argv[1] ?? 'release-49';
$base = "https://raw.githubusercontent.com/unicode-org/cldr/{$release}/common";

$fetch = static function (string $path) use ($base): string {
    $body = file_get_contents("{$base}/{$path}");

    if ($body === false || $body === '') {
        fwrite(STDERR, "Could not fetch {$base}/{$path}\n");
        exit(1);
    }

    return $body;
};

/** CLDR's compact range syntax: "ad02~8" is ad02 to ad08, "ara~h" is ara to arh. */
$expand = static function (string $list): array {
    $out = [];

    foreach (preg_split('/\s+/', trim($list)) ?: [] as $token) {
        if (! str_contains($token, '~')) {
            $out[] = $token;

            continue;
        }

        // The range only ever varies the last character in CLDR's files.
        [$start, $end] = explode('~', $token, 2);

        if (strlen($end) !== 1) {
            fwrite(STDERR, "Unexpected range {$token}\n");
            exit(1);
        }

        for ($c = ord(substr($start, -1)); $c <= ord($end); $c++) {
            $out[] = substr($start, 0, -1).chr($c);
        }
    }

    return $out;
};

$validity = new SimpleXMLElement($fetch('validity/subdivision.xml'));
$metadata = new SimpleXMLElement($fetch('supplemental/supplementalMetadata.xml'));
$names = new SimpleXMLElement($fetch('subdivisions/en.xml'));

$overlong = [];
foreach ($metadata->xpath('//subdivisionAlias[@reason="overlong"]') ?: [] as $alias) {
    $overlong[(string) $alias['type']] = true;
}

$keep = [];
foreach ($validity->xpath('//id[@type="subdivision"]') ?: [] as $group) {
    $status = (string) $group['idStatus'];

    foreach ($expand((string) $group) as $id) {
        if ($status === 'regular' || ($status === 'deprecated' && isset($overlong[$id]))) {
            $keep[$id] = true;
        }
    }
}

$english = [];
foreach ($names->xpath('//subdivision') ?: [] as $name) {
    // CLDR marks some names with footnote digits ("Île-de-France²").
    $english[(string) $name['type']] = trim(preg_replace('/[\x{00B9}\x{00B2}\x{00B3}\x{2070}-\x{2079}]+$/u', '', (string) $name) ?? '');
}

$codes = [];
foreach (array_keys($keep) as $id) {
    $code = strtoupper(substr($id, 0, 2)).'-'.strtoupper(substr($id, 2));

    if (preg_match('/^[A-Z]{2}-[A-Z0-9]{1,3}$/', $code) !== 1) {
        fwrite(STDERR, "Skipping {$id}: not an ISO 3166-2 shape\n");

        continue;
    }

    $codes[$code] = $english[$id] ?? null;
}

ksort($codes, SORT_STRING);

$lines = [];
foreach ($codes as $code => $name) {
    $lines[] = '    '.var_export($code, true).' => '.($name === null ? 'null' : var_export($name, true)).',';
}

$php = <<<PHP
<?php

// GENERATED by bin/build-subdivisions.php from Unicode CLDR {$release}. Do not edit.
// Every current ISO 3166-2 subdivision code, with its English name where CLDR has one.
// Data: Copyright © Unicode, Inc. SPDX-License-Identifier: Unicode-3.0
// https://www.unicode.org/license.txt

return [
%s
];

PHP;

$target = __DIR__.'/../resources/iso-3166-2.php';
@mkdir(dirname($target));
file_put_contents($target, sprintf($php, implode("\n", $lines)));

fwrite(STDOUT, count($codes)." codes written to resources/iso-3166-2.php\n");
